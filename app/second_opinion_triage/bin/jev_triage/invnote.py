"""Investigation summary: the Jev results of all findings in an ES investigation, aggregated, as a Note."""
import json

from . import guide, note

URG = ["low", "medium", "high", "critical"]
L = {
    "en": {"title": "Second Opinion Triage summary of the investigation", "n": "Findings in the investigation: %d",
           "top": "Highest suggested urgency: %s", "disp": "Suggested dispositions: %s", "tp": "Suggested true positive:",
           "und": "Undetermined: %d (need a human decision)", "untr": "Not triaged yet: %d", "err": "Triage errors: %d",
           "ai": "ES AI SOC Analyst disagrees on the disposition: %d", "conf": "Analyst statements moved a true positive away: %d",
           "llm": "Summary (LLM)", "none": "none",
           "foot": "Suggestion only. Decide the investigation in ES. Generated by Second Opinion Triage."},
    "ja": {"title": "セカンドオピニオン トリアージ 調査のまとめ", "n": "調査内の Finding: %d 件",
           "top": "最も高い Urgency（提案）: %s", "disp": "Disposition（提案）の内訳: %s", "tp": "TP と提案した Finding:",
           "und": "判別不可: %d 件（人の判断が必要）", "untr": "未トリアージ: %d 件", "err": "トリアージのエラー: %d 件",
           "ai": "ES AI SOC Analyst と Disposition が食い違う: %d 件", "conf": "申告で TP から結果が変わった: %d 件",
           "llm": "まとめ（LLM）", "none": "なし",
           "foot": "提案のみです。調査の判断は ES で行ってください。Second Opinion Triage により作成。"},
}


def aggregate(items):
    """items: list of dicts {event_id, name, rec (jev_triage_latest or None), ai_cat}. -> summary dict."""
    s = {"n": len(items), "by_disp": {}, "top": "", "tp": [], "und": 0, "untriaged": 0, "errors": 0, "ai_disagree": 0,
         "conflict": 0}
    for it in items:
        r = it.get("rec")
        if not r:
            s["untriaged"] += 1
            continue
        if r.get("jev_status") != "ok":
            s["errors"] += 1
            continue
        d = r.get("jev_disposition") or ""
        s["by_disp"][d] = s["by_disp"].get(d, 0) + 1
        u = r.get("jev_urgency") or ""
        if u in URG and (not s["top"] or URG.index(u) > URG.index(s["top"])):
            s["top"] = u
        if d == "TP":
            ent = ", ".join(x for x in (r.get("user"), r.get("src"), r.get("dest"), r.get("risk_object")) if x)[:80]
            s["tp"].append("%s%s (%s)" % (it.get("name") or r.get("rule_name") or it["event_id"], " — %s" % ent if ent else "", u.capitalize()))
        if d == "Undetermined":
            s["und"] += 1
        a = it.get("ai_cat") or ""
        if a and a != "Undetermined" and d != "Undetermined" and ((d == "TP") != (a == "TP")):
            s["ai_disagree"] += 1
        if str(r.get("jev_statement_conflict")) == "1":
            s["conflict"] += 1
    return s


def build(inv, s, lang="en", llm_text=""):
    T = L.get(lang, L["en"])
    D = note.DISP.get(lang, note.DISP["en"])
    order = ["TP", "Undetermined", "Benign", "FP"]
    disp = ", ".join("%s %d" % (D.get(k, k), s["by_disp"][k]) for k in order if s["by_disp"].get(k)) or T["none"]
    lines = ["%s (%s)" % (inv.get("name") or "", inv.get("display_id") or inv.get("_key")), "",
             T["n"] % s["n"], T["top"] % ((s["top"] or T["none"]).capitalize()), T["disp"] % disp]
    if s["tp"]:
        lines += [T["tp"]] + ["- %s" % x for x in s["tp"][:10]]
    if s["und"]:
        lines.append(T["und"] % s["und"])
    if s["untriaged"]:
        lines.append(T["untr"] % s["untriaged"])
    if s["errors"]:
        lines.append(T["err"] % s["errors"])
    if s["ai_disagree"]:
        lines.append(T["ai"] % s["ai_disagree"])
    if s["conflict"]:
        lines.append(T["conf"] % s["conflict"])
    if llm_text:
        lines += ["", "%s:" % T["llm"], llm_text]
    lines += ["", T["foot"]]
    return T["title"], "\n".join(lines)


def llm_input(inv, items, s):
    """Facts for the LLM summary (no raw logs: the stored Jev facts and results only)."""
    rows = []
    for it in items[:30]:
        r = it.get("rec") or {}
        try:
            facts = (json.loads(r.get("jev_state") or "{}").get("context_from_siem") or [])[:6]
        except (ValueError, AttributeError):
            facts = []
        rows.append({"facts": [guide.clip(str(f), 200) for f in facts],"finding": guide.clip(it.get("name") or r.get("rule_name") or "", 120),
                     "jev_disposition": r.get("jev_disposition") or "not triaged",
                     "jev_confidence": r.get("jev_disposition_confidence"), "jev_urgency": r.get("jev_urgency"),
                     "tactic": r.get("jev_tactic"), "es_ai": it.get("ai_cat") or "",
                     "entities": ", ".join(x for x in (r.get("user"), r.get("src"), r.get("dest")) if x)})
    return {"investigation": {"name": inv.get("name"), "id": inv.get("display_id")},
            "counts": {k: v for k, v in s.items() if k != "tp"}, "findings": rows}
